const _generatedSuffixes = [
  // Flutter and Dart
  '.g.dart', '.freezed.dart', '.mocks.dart', '.gr.dart', '.config.dart', '.pb.dart', '.pbenum.dart', '.pbjson.dart', '.pbserver.dart',
  // JS and TS
  '.min.js', '.min.css', '.min.mjs', '.bundle.js', '.bundle.css', '.chunk.js', '.chunk.css', '.generated.ts', '.generated.js', '.d.ts', '.map',
