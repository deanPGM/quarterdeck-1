final _docPaths = _all([r'\.md$', r'\.mdx$', r'\.rst$', r'\.adoc$', r'(^|/)docs?/', r'(^|/)CHANGELOG', r'(^|/)LICENSE']);

final _generatedHeader = RegExp(r'^// (GENERATED CODE|Generated by|<auto-generated)', caseSensitive: false);

const _largeLines = 1500;

List<RegExp> _all(List<String> sources) => [for (final s in sources) RegExp(s)];

/// A `.skim.yml` rule: paths it matches get its tags on top of the built in ones.
typedef TagRule = ({bool Function(String path) match, List<String> tags});

class ClassifyContext {
  const ClassifyContext({this.generatedByAttributes = const {}, this.formattingOnly = const {}, this.extraGenerated = const [], this.extraTags = const []});

  /// Paths flagged linguist-generated or gitlab-generated in .gitattributes.
  final Set<String> generatedByAttributes;

  /// Paths whose diff is empty when whitespace and blank lines are ignored.
  final Set<String> formattingOnly;

  /// Extra generated globs from .skim.yml, compiled.
  final List<bool Function(String path)> extraGenerated;
  final List<TagRule> extraTags;
}

List<String> classifyFile(DiffFile file, [ClassifyContext ctx = const ClassifyContext()]) {
  final tags = <String>{};
  final p = file.path;
  final name = p.split('/').last;

  if (file.isBinary) tags.add('binary');
  if (_lockFiles.contains(name)) tags.add('lockfile');
  if (ctx.generatedByAttributes.contains(p) ||
      _generatedSuffixes.any(p.endsWith) ||
      _generatedPaths.any((r) => r.hasMatch(p)) ||
      ctx.extraGenerated.any((m) => m(p)) ||
      _generatedHeader.hasMatch(_firstAddedLine(file))) {
    tags.add('generated');
  }
  if (_testPaths.any((r) => r.hasMatch(p))) tags.add('test');
  if (_ciPaths.any((r) => r.hasMatch(p))) tags.add('ci');
  if (_docPaths.any((r) => r.hasMatch(p))) tags.add('docs');
  if ((file.status == 'renamed' || file.status == 'copied') && file.hunks.isEmpty) tags.add('rename-only');
  if (file.additions + file.deletions >= _largeLines) tags.add('large');
  if (ctx.formattingOnly.contains(p) && file.hunks.isNotEmpty) tags.add('formatting-only');
  if (!tags.contains('formatting-only') && file.hunks.isNotEmpty && file.realAdditions == 0 && file.realDeletions == 0 && file.additions + file.deletions > 0) {
    tags.add('moved-only');
  }
  for (final rule in ctx.extraTags) {
    if (rule.match(p)) tags.addAll(rule.tags);
  }
  return tags.toList();
}

String _firstAddedLine(DiffFile file) {
  for (final h in file.hunks) {
    for (final l in h.lines) {
      if (l.type == lineAdd) return l.content;
    }
  }
  return '';
}

/// Paths changed in the full diff but absent from the whitespace insensitive one.
Set<String> formattingOnlyPaths(List<DiffFile> allFiles, List<DiffFile> wsInsensitiveFiles) {
  final changed = {
    for (final f in wsInsensitiveFiles)
      if (f.hunks.isNotEmpty || f.isBinary) f.path,
  };
  return {
    for (final f in allFiles)
      if (f.hunks.isNotEmpty && !changed.contains(f.path)) f.path,
  };
}
