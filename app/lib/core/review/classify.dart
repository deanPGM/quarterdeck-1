];

final _generatedPaths = _all([
  r'(^|/)dist/', r'(^|/)build/', r'(^|/)generated/', r'(^|/)__generated__/', r'(^|/)\.dart_tool/',
  r'(^|/)node_modules/', r'(^|/)Pods/', r'(^|/)\.gradle/', r'(^|/)DerivedData/', r'\.lock$',
  // Flutter localisation output and platform glue
  r'(^|/)lib/l10n/.*\.dart$', r'(^|/)generated_plugin_registrant\.', r'(^|/)GeneratedPluginRegistrant\.',
]);

final _testPaths = _all([
  r'(^|/)test/',
  r'(^|/)tests/',
  r'(^|/)__tests__/',
  r'(^|/)spec/',
  r'(^|/)integration_test/',
